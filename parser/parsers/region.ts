const INVALID_VALUES = new Set([
  "кыргыз коньягы",
  "проявления",
  "ак-суйское мтмв",
  "иссык-атинское м-е тмв",
]);

const LATIN_TO_CYRILLIC: [RegExp, string][] = [
  [/O/g, "О"],  // Latin O → Cyrillic О
  [/o/g, "о"],
  [/c/g, "с"],  // Latin c → Cyrillic с
  [/e/g, "е"],
  [/a/g, "а"],
  [/p/g, "р"],
  [/x/g, "х"],
  [/y/g, "у"],
  [/k/g, "к"],
  [/H/g, "Н"],
  [/B/g, "В"],
];

function normalizeCyrillic(s: string): string {
  for (const [pattern, replacement] of LATIN_TO_CYRILLIC) {
    s = s.replace(pattern, replacement);
  }
  return s;
}

function extractRegion(raw: string): string | null {
  let trimmed = raw.trim();

  if (!trimmed) return null;

  // Normalize latin lookalikes to cyrillic
  trimmed = normalizeCyrillic(trimmed);

  // Check invalid first
  const lowerTrimmed = trimmed.toLowerCase();
  for (const invalid of INVALID_VALUES) {
    if (lowerTrimmed.includes(invalid)) return null;
  }

  // Check exact canonical match first
  if (CANONICAL_REGIONS.includes(trimmed as any)) return trimmed;

  // Check patterns (not anchored, case-insensitive)
  for (const [pattern, replacement] of REGION_PATTERNS) {
    if (pattern.test(trimmed)) {
      return replacement;
    }
  }

  // Fallback: case-insensitive keyword search
  const regionKeywordsLower: [string, string][] = [
    ["баткенская", "Баткенская область"],
    ["джалал-абадская", "Джалал-Абадская область"],
    ["жалал-абадская", "Джалал-Абадская область"],
    ["жалалабатская", "Джалал-Абадская область"],
    ["иссык-кульская", "Иссык-Кульская область"],
    ["ыссык-кульская", "Иссык-Кульская область"],
    ["ысык-кульская", "Иссык-Кульская область"],
    ["иссыккульская", "Иссык-Кульская область"],
    ["ыссыккульская", "Иссык-Кульская область"],
    ["ысыккульская", "Иссык-Кульская область"],
    ["нарынская", "Нарынская область"],
    ["ошская", "Ошская область"],
    ["таласская", "Таласская область"],
    ["чуйская", "Чуйская область"],
    ["г. бишкек", "г. Бишкек"],
    ["г. ош", "г. Ош"],
    ["город бишкек", "г. Бишкек"],
    ["город ош", "г. Ош"],
  ];
  for (const [keyword, canonical] of regionKeywordsLower) {
    if (lowerTrimmed.includes(keyword)) {
      return canonical;
    }
  }

  return null;
}

export function parseRegion(raw: string): Field<CanonicalRegion> {
  const result = extractRegion(raw);
  return { raw, value: (result || "") as CanonicalRegion };
}
